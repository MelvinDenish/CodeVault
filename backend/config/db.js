const oracledb = require('oracledb');
require('dotenv').config();

// oracledb v6+ uses Thin mode by default (no Oracle Client libs needed)
// If you need Thick mode, uncomment: oracledb.initOracleClient();

let pool;

function numberFromEnv(name, fallback) {
  const value = Number.parseInt(process.env[name], 10);
  return Number.isFinite(value) ? value : fallback;
}

function shouldInitializeSchema() {
  return process.env.INIT_SCHEMA !== 'false';
}

async function initDB() {
  try {
    pool = await oracledb.createPool({
      user: process.env.ORACLE_USER || 'system',
      password: process.env.ORACLE_PASSWORD || 'oracle',
      connectionString: process.env.ORACLE_CONNECTION_STRING || 'localhost:1521/FREE',
      poolMin: numberFromEnv('ORACLE_POOL_MIN', 0),
      poolMax: numberFromEnv('ORACLE_POOL_MAX', 4),
      poolIncrement: numberFromEnv('ORACLE_POOL_INCREMENT', 1),
      poolTimeout: numberFromEnv('ORACLE_POOL_TIMEOUT', 60),
      queueTimeout: numberFromEnv('ORACLE_QUEUE_TIMEOUT', 10000)
    });
    console.log('✅ Oracle connection pool created');

    if (shouldInitializeSchema()) {
      await initSchema();
    } else {
      console.log('Schema initialization skipped');
    }

    return pool;
  } catch (err) {
    console.error('❌ Oracle connection failed:', err.message);
    throw err;
  }
}

async function getConnection() {
  return await oracledb.getConnection();
}

async function closePool() {
  if (pool) {
    await pool.close(0);
    console.log('Oracle pool closed');
  }
}

async function initSchema() {
  const conn = await getConnection();
  try {
    const tables = [
      {
        name: 'USERS',
        sql: `CREATE TABLE users (
          user_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          username     VARCHAR2(100) UNIQUE NOT NULL,
          email        VARCHAR2(150) UNIQUE NOT NULL,
          password_hash VARCHAR2(255) NOT NULL,
          avatar_url   VARCHAR2(500),
          bio          VARCHAR2(500),
          created_at   TIMESTAMP DEFAULT SYSTIMESTAMP
        )`
      },
      {
        name: 'REPOSITORIES',
        sql: `CREATE TABLE repositories (
          repo_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_name   VARCHAR2(200) NOT NULL,
          description VARCHAR2(500),
          owner_id    NUMBER NOT NULL,
          visibility  VARCHAR2(20) DEFAULT 'public',
          default_branch VARCHAR2(100) DEFAULT 'main',
          created_at  TIMESTAMP DEFAULT SYSTIMESTAMP,
          updated_at  TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (owner_id) REFERENCES users(user_id) ON DELETE CASCADE
        )`
      },
      {
        name: 'BRANCHES',
        sql: `CREATE TABLE branches (
          branch_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id       NUMBER NOT NULL,
          branch_name   VARCHAR2(100) NOT NULL,
          head_commit_id NUMBER,
          created_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (repo_id) REFERENCES repositories(repo_id) ON DELETE CASCADE
        )`
      },
      {
        name: 'COMMITS',
        sql: `CREATE TABLE commits (
          commit_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id          NUMBER NOT NULL,
          branch_id        NUMBER NOT NULL,
          author_id        NUMBER NOT NULL,
          message          VARCHAR2(500),
          parent_commit_id NUMBER,
          commit_hash      VARCHAR2(64),
          commit_time      TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (repo_id)   REFERENCES repositories(repo_id) ON DELETE CASCADE,
          FOREIGN KEY (branch_id) REFERENCES branches(branch_id) ON DELETE CASCADE,
          FOREIGN KEY (author_id) REFERENCES users(user_id)
        )`
      },
      {
        name: 'FILES',
        sql: `CREATE TABLE files (
          file_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          commit_id    NUMBER NOT NULL,
          file_path    VARCHAR2(500) NOT NULL,
          file_hash    VARCHAR2(200) NOT NULL,
          file_content CLOB,
          file_size    NUMBER DEFAULT 0,
          FOREIGN KEY (commit_id) REFERENCES commits(commit_id) ON DELETE CASCADE
        )`
      },
      {
        name: 'PULL_REQUESTS',
        sql: `CREATE TABLE pull_requests (
          pr_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id       NUMBER NOT NULL,
          title         VARCHAR2(300),
          description   VARCHAR2(2000),
          source_branch NUMBER NOT NULL,
          target_branch NUMBER NOT NULL,
          author_id     NUMBER NOT NULL,
          status        VARCHAR2(50) DEFAULT 'open',
          created_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
          updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
          merged_at     TIMESTAMP,
          FOREIGN KEY (repo_id)       REFERENCES repositories(repo_id) ON DELETE CASCADE,
          FOREIGN KEY (source_branch) REFERENCES branches(branch_id),
          FOREIGN KEY (target_branch) REFERENCES branches(branch_id),
          FOREIGN KEY (author_id)     REFERENCES users(user_id)
        )`
      },
      {
        name: 'COLLABORATORS',
        sql: `CREATE TABLE collaborators (
          collab_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id      NUMBER NOT NULL,
          user_id      NUMBER NOT NULL,
          role         VARCHAR2(50) DEFAULT 'viewer',
          created_at   TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (repo_id) REFERENCES repositories(repo_id) ON DELETE CASCADE,
          FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
        )`
      },
      {
        name: 'ISSUES',
        sql: `CREATE TABLE issues (
          issue_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          repo_id       NUMBER NOT NULL,
          title         VARCHAR2(300) NOT NULL,
          description   CLOB,
          status        VARCHAR2(50) DEFAULT 'open',
          created_by    NUMBER,
          assignee_id   NUMBER,
          created_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
          updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
          closed_at     TIMESTAMP,
          FOREIGN KEY (repo_id)    REFERENCES repositories(repo_id) ON DELETE CASCADE,
          FOREIGN KEY (created_by) REFERENCES users(user_id),
          FOREIGN KEY (assignee_id) REFERENCES users(user_id)
        )`
      },
      {
        name: 'ISSUE_COMMENTS',
        sql: `CREATE TABLE issue_comments (
          comment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          issue_id     NUMBER NOT NULL,
          user_id      NUMBER NOT NULL,
          body         CLOB NOT NULL,
          created_at   TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (issue_id) REFERENCES issues(issue_id) ON DELETE CASCADE,
          FOREIGN KEY (user_id)  REFERENCES users(user_id)
        )`
      },
      {
        name: 'FORKS',
        sql: `CREATE TABLE forks (
          fork_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          original_repo  NUMBER NOT NULL,
          forked_repo    NUMBER NOT NULL,
          forked_by      NUMBER NOT NULL,
          created_at     TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (original_repo) REFERENCES repositories(repo_id),
          FOREIGN KEY (forked_repo)   REFERENCES repositories(repo_id) ON DELETE CASCADE,
          FOREIGN KEY (forked_by)     REFERENCES users(user_id)
        )`
      },
      {
        name: 'ACTIVITY_LOGS',
        sql: `CREATE TABLE activity_logs (
          log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id     NUMBER,
          repo_id     NUMBER,
          action      VARCHAR2(50) NOT NULL,
          details     VARCHAR2(500),
          action_time TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (user_id) REFERENCES users(user_id),
          FOREIGN KEY (repo_id) REFERENCES repositories(repo_id) ON DELETE CASCADE
        )`
      },
      {
        name: 'STARS',
        sql: `CREATE TABLE stars (
          star_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id     NUMBER NOT NULL,
          repo_id     NUMBER NOT NULL,
          created_at  TIMESTAMP DEFAULT SYSTIMESTAMP,
          FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
          FOREIGN KEY (repo_id) REFERENCES repositories(repo_id) ON DELETE CASCADE,
          CONSTRAINT uk_stars UNIQUE (user_id, repo_id)
        )`
      }
    ];

    for (const table of tables) {
      try {
        const check = await conn.execute(
          `SELECT COUNT(*) AS cnt FROM user_tables WHERE table_name = :name`,
          { name: table.name }
        );
        if (check.rows[0][0] === 0) {
          await conn.execute(table.sql);
          console.log(`  Created table: ${table.name}`);
        }
      } catch (err) {
        if (err.errorNum !== 955) { // ORA-00955: name already used
          console.error(`  Error creating ${table.name}:`, err.message);
        }
      }
    }

    // Create triggers
    const triggers = [
      {
        name: 'TRG_DEFAULT_BRANCH',
        sql: `CREATE OR REPLACE TRIGGER trg_default_branch
          AFTER INSERT ON repositories
          FOR EACH ROW
          BEGIN
            INSERT INTO branches(repo_id, branch_name, head_commit_id)
            VALUES(:NEW.repo_id, 'main', NULL);
          END;`
      },
      {
        name: 'TRG_LOG_COMMIT',
        sql: `CREATE OR REPLACE TRIGGER trg_log_commit
          AFTER INSERT ON commits
          FOR EACH ROW
          BEGIN
            INSERT INTO activity_logs(user_id, repo_id, action, details)
            VALUES(:NEW.author_id, :NEW.repo_id, 'commit', 
              'Created commit #' || :NEW.commit_id);
          END;`
      },
      {
        name: 'TRG_LOG_PR',
        sql: `CREATE OR REPLACE TRIGGER trg_log_pr
          AFTER INSERT ON pull_requests
          FOR EACH ROW
          BEGIN
            INSERT INTO activity_logs(user_id, repo_id, action, details)
            VALUES(:NEW.author_id, :NEW.repo_id, 'pull_request', 
              'Created PR #' || :NEW.pr_id);
          END;`
      }
    ];

    for (const trigger of triggers) {
      try {
        await conn.execute(trigger.sql);
        console.log(`  Created trigger: ${trigger.name}`);
      } catch (err) {
        // Triggers with CREATE OR REPLACE should not fail
        if (!err.message.includes('already exists')) {
          console.error(`  Error creating trigger ${trigger.name}:`, err.message);
        }
      }
    }

    const indexes = [
      {
        name: 'IDX_REPOS_OWNER_CREATED',
        sql: 'CREATE INDEX idx_repos_owner_created ON repositories(owner_id, created_at DESC)'
      },
      {
        name: 'IDX_REPOS_VISIBILITY_CREATED',
        sql: 'CREATE INDEX idx_repos_visibility_created ON repositories(visibility, created_at DESC)'
      },
      {
        name: 'IDX_BRANCHES_REPO_NAME',
        sql: 'CREATE INDEX idx_branches_repo_name ON branches(repo_id, branch_name)'
      },
      {
        name: 'IDX_COMMITS_REPO_TIME',
        sql: 'CREATE INDEX idx_commits_repo_time ON commits(repo_id, commit_time DESC)'
      },
      {
        name: 'IDX_COMMITS_REPO_BRANCH_TIME',
        sql: 'CREATE INDEX idx_commits_repo_branch_time ON commits(repo_id, branch_id, commit_time DESC)'
      },
      {
        name: 'IDX_FILES_COMMIT_PATH',
        sql: 'CREATE INDEX idx_files_commit_path ON files(commit_id, file_path)'
      },
      {
        name: 'IDX_ISSUES_REPO_STATUS_CREATED',
        sql: 'CREATE INDEX idx_issues_repo_status_created ON issues(repo_id, status, created_at DESC)'
      },
      {
        name: 'IDX_ISSUE_COMMENTS_ISSUE_CREATED',
        sql: 'CREATE INDEX idx_issue_comments_issue_created ON issue_comments(issue_id, created_at)'
      },
      {
        name: 'IDX_PRS_REPO_STATUS_CREATED',
        sql: 'CREATE INDEX idx_prs_repo_status_created ON pull_requests(repo_id, status, created_at DESC)'
      },
      {
        name: 'IDX_COLLAB_REPO_USER',
        sql: 'CREATE INDEX idx_collab_repo_user ON collaborators(repo_id, user_id)'
      },
      {
        name: 'IDX_ACTIVITY_REPO_TIME',
        sql: 'CREATE INDEX idx_activity_repo_time ON activity_logs(repo_id, action_time DESC)'
      },
      {
        name: 'IDX_STARS_REPO',
        sql: 'CREATE INDEX idx_stars_repo ON stars(repo_id)'
      }
    ];

    for (const index of indexes) {
      try {
        const check = await conn.execute(
          `SELECT COUNT(*) AS cnt FROM user_indexes WHERE index_name = :name`,
          { name: index.name }
        );
        if (check.rows[0][0] === 0) {
          await conn.execute(index.sql);
          console.log(`  Created index: ${index.name}`);
        }
      } catch (err) {
        if (err.errorNum !== 955) {
          console.error(`  Error creating index ${index.name}:`, err.message);
        }
      }
    }

    await conn.commit();
    console.log('✅ Schema initialization complete');
  } catch (err) {
    console.error('Schema init error:', err.message);
  } finally {
    await conn.close();
  }
}

module.exports = { initDB, getConnection, closePool };
